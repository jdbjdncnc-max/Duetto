import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(scriptDir, '..');
const packageRoot = path.join(projectRoot, 'frontend', 'pkg');
const listenRoot = path.join(packageRoot, 'listen');
const babelPath = path.join(packageRoot, 'vendor', 'babel.js');
const outputPath = path.join(listenRoot, 'app.bundle.js');

const runtimeSources = [
  'ombre-embed.js',
  'image-slot.js',
  'claude-bridge.js',
  'auth.js',
  'vendor/react.js',
  'vendor/react-dom.js',
];

const sources = [
  'data.jsx',
  'store.jsx',
  'widgets.jsx',
  'features.jsx',
  'features2.jsx',
  'views.jsx',
  'views3.jsx',
  'book.jsx',
  'reader.jsx',
  'app.jsx',
];

const context = { console, setTimeout, clearTimeout };
context.self = context;
context.window = context;
context.globalThis = context;
vm.createContext(context);
vm.runInContext(fs.readFileSync(babelPath, 'utf8'), context, { filename: babelPath });

if (!context.Babel || typeof context.Babel.transform !== 'function') {
  throw new Error('Unable to load the vendored Babel compiler.');
}

const input = sources.map((name) => {
  const sourcePath = path.join(listenRoot, name);
  return `/* source: ${name} */\n${fs.readFileSync(sourcePath, 'utf8')}`;
}).join('\n;\n');

const result = context.Babel.transform(input, {
  presets: [['react', { runtime: 'classic' }]],
  sourceType: 'script',
  compact: true,
  comments: false,
  filename: 'listen/app.bundle.jsx',
});

const runtime = runtimeSources.map((name) => {
  return fs.readFileSync(path.join(packageRoot, name), 'utf8').trimEnd();
});
runtime.push(result.code.trimEnd());
runtime.push(fs.readFileSync(path.join(packageRoot, 'sync.js'), 'utf8').trimEnd());

const banner = '/* Generated by npm run build:frontend. Edit the source files, not this bundle. */\n';
const bundle = banner + runtime.join('\n;\n') + '\n';
fs.writeFileSync(outputPath, bundle);
console.log(`Built ${path.relative(projectRoot, outputPath)} (${Buffer.byteLength(bundle)} bytes)`);
